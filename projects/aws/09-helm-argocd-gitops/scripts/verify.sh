#!/usr/bin/env bash
# Verifies AWS 09: Argo CD healthy, app-of-apps created both environments from Git, dev runs the digest
# in Git, prod gated, AppProject restrictions in place, and self-heal reverts drift in dev.
set -euo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd "$HERE/../../../.." && pwd)
# shellcheck source=../../../../shared/scripts/lib.sh
source "$ROOT/shared/scripts/lib.sh"
require_cmd kubectl jq python3

app() { kubectl -n argocd get application "$1" -o json 2>/dev/null || echo '{}'; }
st() { jq -r '(.status.sync.status // "missing") + "/" + (.status.health.status // "missing")' <<<"$(app "$1")"; }

info "Argo CD"
notready=$(kubectl -n argocd get pods --no-headers | awk '{split($2,a,"/"); if (a[1]!=a[2] || $3!="Running") print $1}' | wc -l)
(( notready == 0 )) && pass "all Argo CD pods ready ($(kubectl -n argocd get pods --no-headers | wc -l))" || fail "$notready Argo CD pod(s) not ready"
kubectl -n argocd get deploy argocd-dex-server >/dev/null 2>&1 && warn "Dex is installed (not needed in the lab)" || pass "minimal install: no Dex"

info "App of apps"
[[ $(st gitops-root) == Synced/Healthy ]] && pass "gitops-root Synced/Healthy" || fail "gitops-root: $(st gitops-root)"
for a in taskboard-dev taskboard-prod; do
  [[ $(app "$a") != '{}' ]] && pass "$a generated by the ApplicationSet" || fail "$a missing"
done
dests=$(kubectl -n argocd get appproject taskboard -o jsonpath='{.spec.destinations[*].namespace}')
[[ "$dests" == "taskboard-dev taskboard-prod" ]] && pass "AppProject limits destinations to: $dests" || fail "AppProject destinations: $dests"
repos=$(kubectl -n argocd get appproject taskboard -o jsonpath='{.spec.sourceRepos[*]}')
[[ "$repos" != *'*'* ]] && pass "AppProject allows one source repository" || fail "AppProject sourceRepos: $repos"

info "dev (automated)"
[[ $(st taskboard-dev) == Synced/Healthy ]] && pass "taskboard-dev Synced/Healthy" || fail "taskboard-dev: $(st taskboard-dev)"
want=$(python3 -c "import re;s=open('$HERE/../environments/dev/values.yaml').read();print(re.search(r'^  digest: (\S+)',s,re.M).group(1))")
running=$(kubectl -n taskboard-dev get deploy taskboard -o jsonpath='{.spec.template.spec.containers[0].image}' 2>/dev/null || true)
[[ "$running" == *"@$want" ]] && pass "dev runs the digest committed in Git" || fail "dev image '$running' vs Git $want"
[[ $(kubectl get ns taskboard-dev -o jsonpath='{.metadata.labels.pod-security\.kubernetes\.io/enforce}') == restricted ]] \
  && pass "namespace created by Argo CD with Pod Security restricted" || fail "PSA label missing on taskboard-dev"

info "Self-heal (drift in dev is reverted)"
kubectl -n taskboard-dev scale deploy/taskboard --replicas=3 >/dev/null
healed=0
for _ in $(seq 1 36); do
  [[ $(kubectl -n taskboard-dev get deploy taskboard -o jsonpath='{.spec.replicas}') == 1 ]] && { healed=1; break; }
  sleep 5
done
(( healed )) && pass "manual scale to 3 reverted to Git's 1 replica" || fail "drift not reverted within 3 minutes"

info "prod (manual)"
[[ $(app taskboard-prod | jq -r '.spec.syncPolicy.automated // "none"') == none ]] && pass "prod has no automated sync (human gate)" || fail "prod is auto-synced"
pass "prod status: $(st taskboard-prod)  (OutOfSync until you run scripts/sync-prod.sh)"

finish
